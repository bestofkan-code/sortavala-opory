# -*- coding: utf-8 -*-
"""Новые виды работ в окне опоры: 15 — «Повторное заземление» (контур смонтирован),
16 — «Установлен цоколь» (фасадный цоколь на фланец). 11 — «Котлован под заземление» уже был.
Применять к каждой странице: python3 tools/patch_works15.py <file.html> [...]"""
import sys
R = [('[11, "Котлован под заземление"], ', '[11, "Котлован под заземление"], [15, "Повторное заземление"], '),
     ('[4, "Установлена опора"], ', '[4, "Установлена опора"], [16, "Установлен цоколь"], '),
     ("14:'Подрезка (бриг.)',13:'Вывоз отходов'}", "14:'Подрезка (бриг.)',13:'Вывоз отходов',15:'Повт. заземление',16:'Цоколь'}")]
for f in sys.argv[1:]:
    s = open(f, encoding='utf-8').read()
    if '[15, "Повторное заземление"]' in s:
        print(f, 'уже применён'); continue
    c = []
    for a, b in R:
        c.append(s.count(a)); s = s.replace(a, b)
    open(f, 'w', encoding='utf-8').write(s); print(f, c)
